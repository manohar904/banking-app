-- Ledger of completed deposits and withdrawals. Rows are only ever inserted.
CREATE TABLE account_transactions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- No cascade: an account with history cannot be deleted.
    account_id    BIGINT         NOT NULL REFERENCES accounts (id),
    type          VARCHAR(20)    NOT NULL CHECK (type IN ('DEPOSIT', 'WITHDRAWAL')),
    amount        NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    balance_after NUMERIC(19, 2) NOT NULL CHECK (balance_after >= 0),
    created_at    TIMESTAMPTZ    NOT NULL
);

CREATE INDEX idx_account_transactions_account_id ON account_transactions (account_id, id);
