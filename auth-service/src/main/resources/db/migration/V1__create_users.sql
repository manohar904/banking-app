-- Sign-in accounts. Staff have no customer record; every customer login belongs to one customer.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('STAFF', 'CUSTOMER')),
    -- Customers live in the customer service's database, so there is no foreign key.
    -- That service removes the login when it deletes a customer.
    customer_id   BIGINT       UNIQUE,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT users_customer_matches_role CHECK ((role = 'CUSTOMER') = (customer_id IS NOT NULL))
);
